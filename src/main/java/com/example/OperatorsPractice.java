package com.example;

public class OperatorsPractice {
    public static void main(String[] args){
        int a = 10 , b = 4;


        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);

        double d = (double) a/b;
        System.out.println(d);

        System.out.println("Result: " + 5 + 5);
        System.out.println("Result: " + (5 + 5));

        double x = 7.9;
        int i = (int) x;
        System.out.println(i);

    }



}
